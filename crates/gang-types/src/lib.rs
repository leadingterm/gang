//! Shared value types for Gang: sizes, durations, instruction sets, validated
//! names, PEM certificates and secrets.
//!
//! ```
//! use gang_types::{Bytes, duration};
//! use std::time::Duration;
//!
//! let memory = "29GiB".parse::<Bytes>()?;
//! assert_eq!(memory.get(), 29 * 1024 * 1024 * 1024);
//!
//! let timeout = duration::parse("10m")?;
//! assert_eq!(timeout, Duration::from_mins(10));
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```

